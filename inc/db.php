<?php
/** PDO connection + schema. Works on SQLite and MySQL. */

function db()
{
    static $pdo = null;
    if ($pdo !== null) return $pdo;

    $opt = array(
        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES   => false,
    );

    if (DB_DRIVER === 'pgsql') {
        // Neon and other hosted Postgres. Use the POOLED connection string on
        // serverless platforms, or connections are exhausted very quickly.
        $dsn = 'pgsql:host=' . DB_HOST . ';port=' . (defined('DB_PORT') ? DB_PORT : '5432')
             . ';dbname=' . DB_NAME . ';sslmode=require';
        $pdo = new PDO($dsn, DB_USER, DB_PASS, $opt);
    } elseif (DB_DRIVER === 'mysql') {
        $dsn = 'mysql:host=' . DB_HOST . ';port=' . DB_PORT . ';dbname=' . DB_NAME . ';charset=utf8mb4';
        $pdo = new PDO($dsn, DB_USER, DB_PASS, $opt);
    } else {
        $dir = dirname(DB_SQLITE_PATH);
        if (!is_dir($dir)) @mkdir($dir, 0755, true);
        $pdo = new PDO('sqlite:' . DB_SQLITE_PATH, null, null, $opt);
        $pdo->exec('PRAGMA foreign_keys = ON');
        $pdo->exec('PRAGMA journal_mode = WAL');
    }
    return $pdo;
}

function db_is_mysql()
{
    return DB_DRIVER === 'mysql';
}

function db_is_pgsql()
{
    return DB_DRIVER === 'pgsql';
}

/**
 * Case-insensitive LIKE. MySQL and SQLite are already insensitive by default;
 * Postgres is not, and needs ILIKE.
 */
function db_like()
{
    return db_is_pgsql() ? 'ILIKE' : 'LIKE';
}

/** Returns the CREATE TABLE statements for the current driver. */
function db_schema()
{
    $my = db_is_mysql();
    $pg = db_is_pgsql();
    $id = $pg ? 'INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : ($my ? 'INT AUTO_INCREMENT PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT');
    $money = $pg ? 'NUMERIC(18,2) NOT NULL DEFAULT 0'
        : ($my ? 'DECIMAL(18,2) NOT NULL DEFAULT 0' : 'REAL NOT NULL DEFAULT 0');
    $txt = 'TEXT';
    $now = $pg ? 'created_at TIMESTAMP' : 'created_at DATETIME';
    $suffix = $my ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : '';

    $t = array();
    // Postgres has no TINYINT or DATETIME; map them as the statements are built.
    $fix = function ($sql) use ($pg) {
        if (!$pg) return $sql;
        $sql = preg_replace('/\bTINYINT\(1\)|\bTINYINT\b/i', 'SMALLINT', $sql);
        $sql = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $sql);
        return $sql;
    };

    $t[] = "CREATE TABLE IF NOT EXISTS settings (
        skey VARCHAR(64) PRIMARY KEY,
        svalue $txt
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS users (
        id $id,
        first_name VARCHAR(60),
        last_name VARCHAR(60),
        email VARCHAR(160) UNIQUE,
        phone VARCHAR(40),
        password VARCHAR(255),
        role VARCHAR(10) DEFAULT 'user',
        status VARCHAR(20) DEFAULT 'pending',
        account_number VARCHAR(20),
        account_type VARCHAR(30) DEFAULT 'Savings',
        currency VARCHAR(5) DEFAULT 'USD',
        balance $money,
        pin VARCHAR(255),
        email_verified INTEGER DEFAULT 0,
        verify_token VARCHAR(80),
        reset_token VARCHAR(80),
        reset_expires DATETIME,
        otp_code VARCHAR(10),
        otp_expires DATETIME,
        two_factor INTEGER DEFAULT 0,
        kyc_status VARCHAR(20) DEFAULT 'unverified',
        avatar VARCHAR(255),
        dob VARCHAR(20),
        gender VARCHAR(12),
        occupation VARCHAR(80),
        address $txt,
        city VARCHAR(60),
        state VARCHAR(60),
        country VARCHAR(60),
        zip VARCHAR(20),
        transfer_locked INTEGER DEFAULT 0,
        lock_reason $txt,
        last_login DATETIME,
        last_ip VARCHAR(60),
        $now,
        updated_at DATETIME
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS transactions (
        id $id,
        user_id INTEGER NOT NULL,
        ref VARCHAR(40),
        direction VARCHAR(10),
        category VARCHAR(30),
        amount $money,
        fee $money,
        balance_after $money,
        description $txt,
        channel VARCHAR(30),
        counterparty VARCHAR(160),
        status VARCHAR(20) DEFAULT 'completed',
        meta $txt,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS transfers (
        id $id,
        user_id INTEGER NOT NULL,
        ref VARCHAR(40),
        kind VARCHAR(20),
        amount $money,
        fee $money,
        total $money,
        beneficiary_name VARCHAR(160),
        beneficiary_account VARCHAR(60),
        bank_name VARCHAR(160),
        bank_address $txt,
        swift VARCHAR(40),
        routing VARCHAR(40),
        iban VARCHAR(60),
        country VARCHAR(60),
        narration $txt,
        status VARCHAR(20) DEFAULT 'pending',
        admin_note $txt,
        approved_by INTEGER,
        approved_at DATETIME,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS deposits (
        id $id,
        user_id INTEGER NOT NULL,
        ref VARCHAR(40),
        amount $money,
        method VARCHAR(40),
        proof VARCHAR(255),
        note $txt,
        status VARCHAR(20) DEFAULT 'pending',
        admin_note $txt,
        approved_by INTEGER,
        approved_at DATETIME,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS withdrawals (
        id $id,
        user_id INTEGER NOT NULL,
        ref VARCHAR(40),
        amount $money,
        fee $money,
        method VARCHAR(40),
        destination $txt,
        status VARCHAR(20) DEFAULT 'pending',
        admin_note $txt,
        approved_by INTEGER,
        approved_at DATETIME,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS loans (
        id $id,
        user_id INTEGER NOT NULL,
        ref VARCHAR(40),
        amount $money,
        interest_rate REAL DEFAULT 0,
        tenure_months INTEGER DEFAULT 12,
        monthly_payment $money,
        total_repayable $money,
        amount_repaid $money,
        purpose VARCHAR(120),
        details $txt,
        employment VARCHAR(60),
        monthly_income $money,
        collateral $txt,
        status VARCHAR(20) DEFAULT 'pending',
        admin_note $txt,
        approved_by INTEGER,
        disbursed_at DATETIME,
        due_at DATETIME,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS loan_repayments (
        id $id,
        loan_id INTEGER NOT NULL,
        user_id INTEGER NOT NULL,
        amount $money,
        ref VARCHAR(40),
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS cards (
        id $id,
        user_id INTEGER NOT NULL,
        card_type VARCHAR(20),
        brand VARCHAR(20),
        number VARCHAR(30),
        cvv VARCHAR(6),
        expiry VARCHAR(10),
        card_pin VARCHAR(255),
        spend_limit $money,
        status VARCHAR(20) DEFAULT 'pending',
        admin_note $txt,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS beneficiaries (
        id $id,
        user_id INTEGER NOT NULL,
        name VARCHAR(160),
        account_number VARCHAR(60),
        bank_name VARCHAR(160),
        swift VARCHAR(40),
        country VARCHAR(60),
        kind VARCHAR(20) DEFAULT 'domestic',
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS messages (
        id $id,
        user_id INTEGER,
        subject VARCHAR(200),
        body $txt,
        is_read INTEGER DEFAULT 0,
        emailed INTEGER DEFAULT 0,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS kyc_documents (
        id $id,
        user_id INTEGER NOT NULL,
        doc_type VARCHAR(60),
        id_number VARCHAR(80),
        front VARCHAR(255),
        back VARCHAR(255),
        status VARCHAR(20) DEFAULT 'pending',
        note $txt,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS transfer_codes (
        id $id,
        user_id INTEGER NOT NULL,
        code_type VARCHAR(20),
        code VARCHAR(40),
        used INTEGER DEFAULT 0,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS audit_log (
        id $id,
        actor_id INTEGER,
        actor_name VARCHAR(120),
        action VARCHAR(80),
        entity VARCHAR(40),
        entity_id INTEGER,
        details $txt,
        ip VARCHAR(60),
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS enquiries (
        id $id,
        kind VARCHAR(20),
        name VARCHAR(120),
        email VARCHAR(160),
        phone VARCHAR(40),
        subject VARCHAR(200),
        message $txt,
        meta $txt,
        status VARCHAR(20) DEFAULT 'new',
        admin_note $txt,
        $now
    )$suffix";

    $t[] = "CREATE TABLE IF NOT EXISTS login_attempts (
        id $id,
        email VARCHAR(160),
        ip VARCHAR(60),
        success INTEGER DEFAULT 0,
        $now
    )$suffix";

    foreach ($t as $i => $sql) $t[$i] = $fix($sql);

    return $t;
}

function db_install()
{
    $pdo = db();
    foreach (db_schema() as $sql) {
        $pdo->exec($sql);
    }
    $idx = array(
        'CREATE INDEX IF NOT EXISTS idx_tx_user ON transactions (user_id)',
        'CREATE INDEX IF NOT EXISTS idx_tx_created ON transactions (created_at)',
        'CREATE INDEX IF NOT EXISTS idx_tr_user ON transfers (user_id)',
        'CREATE INDEX IF NOT EXISTS idx_dep_user ON deposits (user_id)',
        'CREATE INDEX IF NOT EXISTS idx_loan_user ON loans (user_id)',
        'CREATE INDEX IF NOT EXISTS idx_msg_user ON messages (user_id)',
    );
    foreach ($idx as $sql) {
        try { $pdo->exec($sql); } catch (Exception $e) { /* mysql <8 tolerance */ }
    }
}
